package Basico;

public class WhileAndFor {
    public static void main(String[] args) {
        System.out.println("Naruto vai usar um jutsu!");

        int count = 10;
        for (int i = 0; i < count; i++) {
            System.out.println("Naruto: Jutsu Clone das Sombras! ✋ \uD83D\uDC48");
        }

        System.out.println("Naruto: Jutsu " + count + " Clones das Sombras!");
    }
}
